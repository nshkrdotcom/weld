defmodule Weld.Core.Manifest do
  @moduledoc "Pure, closed validation and normalization of the schema 2 manifest."

  alias Weld.Core.Inventory
  alias Weld.Error

  @roles ~w(compile runtime native test docs metadata lock generation structure verification)a
  @root [
    schema: [type: {:in, [2]}, required: true],
    workspace: [type: :keyword_list, required: true],
    classify: [type: :keyword_list, default: []],
    publication: [type: :keyword_list, default: []],
    dependencies: [type: :any, default: []],
    project_inputs: [type: :any, default: []],
    artifacts: [type: :any, required: true]
  ]
  @workspace [root: [type: :string, required: true], projects: [type: {:list, :string}, required: true]]
  @classify [tooling: [type: {:list, :string}, default: []], proofs: [type: {:list, :string}, default: []], ignored: [type: {:list, :string}, default: []]]
  @publication [internal_only: [type: {:list, :string}, default: []], separate: [type: {:list, :string}, default: []], optional: [type: :any, default: []]]
  @artifact [
    layout: [type: {:in, [:components, :flat, :preserve]}, required: true],
    roots: [type: {:list, :string}, required: true],
    include: [type: {:list, :string}, default: []],
    features: [type: {:list, :string}, default: []],
    external: [type: {:list, :string}, default: []],
    inputs: [type: {:list, :keyword_list}, default: []],
    package: [type: :keyword_list], docs: [type: :keyword_list], files: [type: :keyword_list],
    preserve: [type: :keyword_list], flat: [type: :keyword_list], verify: [type: :keyword_list, default: []]
  ]
  @package [
    name: [type: :string, required: true], otp_app: [type: :atom, required: true],
    version: [type: :string, required: true], elixir: [type: :string, default: "~> 1.18"],
    description: [type: :string, default: "Generated by Weld"],
    licenses: [type: {:list, :string}, default: ["MIT"]], links: [type: :any, default: %{}],
    dev_deps: [type: {:list, :any}, default: []]
  ]
  @docs [
    main: [type: :string, default: "readme"], logo: [type: :string],
    homepage_url: [type: :string], source_url: [type: :string], source_ref: [type: :string],
    assets: [type: :any, default: %{}], extra_titles: [type: :any, default: %{}],
    groups_for_extras: [type: :any, default: []], mermaid: [type: :boolean, default: false],
    hook_file: [type: :string]
  ]
  @files [docs: [type: {:list, :string}, default: []], assets: [type: {:list, :string}, default: []]]
  @preserve [files: [type: {:list, :string}, required: true], inputs: [type: {:list, :keyword_list}, default: []]]
  @flat [readme: [type: :string], shared_test_configs: [type: {:list, :string}, default: []], extra_test_deps: [type: {:list, :atom}, default: []], test_support: [type: {:list, :string}, default: []]]
  @verify [
    artifact_tests: [type: {:list, :string}, default: []], component_tests: [type: :boolean, default: false],
    hex_build: [type: :boolean, default: true], hex_publish_check: [type: :boolean, default: true],
    smoke: [type: :any, default: nil], context: [type: {:list, :string}, default: []]
  ]
  @smoke [entry_file: [type: :string, required: true]]
  @input [path: [type: :string, required: true], type: [type: {:in, [:file, :tree, :glob]}, required: true], required: [type: :boolean, default: true]]
  @project_input @input ++ [roles: [type: {:list, {:in, @roles}}, required: true], target: [type: {:in, [:relative, :none]}, required: true], publish: [type: :boolean]]
  @dependency [requirement: [type: :any, default: nil], opts: [type: :keyword_list, default: []]]
  @dep_opts [
    git: [type: :string], github: [type: :string], branch: [type: :string], tag: [type: :string], ref: [type: :string],
    subdir: [type: :string], sparse: [type: :string], submodules: [type: :boolean], depth: [type: :pos_integer],
    hex: [type: :any], repo: [type: :string], organization: [type: :string],
    only: [type: :any], targets: [type: :any], env: [type: :atom],
    runtime: [type: :boolean], optional: [type: :boolean], override: [type: :boolean],
    app: [type: :any], compile: [type: :any], manager: [type: :atom], system_env: [type: :any]
  ]

  @spec normalize(term()) :: {:ok, keyword()} | {:error, [map()]}
  def normalize(term) do
    case audit(term) do
      [] -> {:ok, normalize_term!(term)}
      errors -> {:error, errors}
    end
  rescue
    error in [ArgumentError, NimbleOptions.ValidationError] ->
      {:error, [diagnostic(:invalid_manifest, "manifest", Exception.message(error))]}
  catch
    {:manifest_error, diagnostic} -> {:error, [diagnostic]}
  end

  def normalize!(term) do
    case normalize(term) do
      {:ok, value} -> value
      {:error, errors} ->
        raise Error, message: Enum.map_join(errors, "\n", & &1.message), code: :invalid_manifest,
          phase: :manifest, diagnostics: errors
    end
  end

  defp normalize_term!(raw) do
    config = validate!(raw, @root, "manifest")
    workspace = validate!(config[:workspace], @workspace, "workspace")
    workspace_root!(workspace[:root])
    projects = paths!(workspace[:projects], "workspace.projects", true, true)
    nonempty!(projects, "workspace.projects")
    classify = validate!(config[:classify], @classify, "classify")
    classify = Enum.map(classify, fn {key, ids} -> {key, paths!(ids, "classify.#{key}", true)} end)
    disjoint!(classify, "classify")
    publication = validate!(config[:publication], @publication, "publication")
    optional = named!(publication[:optional], "publication.optional") |> Enum.map(fn {feature, ids} ->
      id = name!(feature, "publication.optional")
      {id, paths!(ids, "publication.optional.#{id}", true)}
    end)
    publication = publication |> Keyword.put(:internal_only, paths!(publication[:internal_only], "publication.internal_only", true))
      |> Keyword.put(:separate, paths!(publication[:separate], "publication.separate", true)) |> Keyword.put(:optional, optional)
    disjoint!(Keyword.take(publication, [:internal_only, :separate]) ++ optional, "publication")
    dependencies = named!(config[:dependencies], "dependencies") |> Enum.map(fn {app, value} ->
      unless is_atom(app) and app not in [nil, true, false], do: fail!(:invalid_dependency, "dependencies", "dependency app keys must be atoms")
      {app, dependency!(value, "dependencies.#{app}")}
    end) |> Enum.sort_by(fn {app, _} -> Atom.to_string(app) end)
    inputs = named!(config[:project_inputs], "project_inputs") |> Map.new(fn {id, declarations} ->
      id = to_string(id)
      path!(id, "project_inputs.#{id}", true)
      {id, declarations!(declarations, true, "project_inputs.#{id}")}
    end)
    artifacts = named!(config[:artifacts], "artifacts") |> Enum.map(fn {id, value} ->
      id = name!(id, "artifacts")
      {id, artifact!(value, id, optional)}
    end) |> Enum.sort_by(&elem(&1, 0))
    nonempty!(artifacts, "artifacts")
    config |> Keyword.put(:workspace, Keyword.put(workspace, :projects, projects))
      |> Keyword.put(:classify, classify) |> Keyword.put(:publication, publication)
      |> Keyword.put(:dependencies, dependencies) |> Keyword.put(:project_inputs, inputs)
      |> Keyword.put(:artifacts, artifacts)
  end

  defp artifact!(raw, name, optional) do
    at = "artifacts.#{name}"
    a = validate!(raw, @artifact, at)
    a = Enum.reduce([:roots, :include, :external], a, fn key, acc -> Keyword.put(acc, key, paths!(a[key], "#{at}.#{key}", true)) end)
    nonempty!(a[:roots], "#{at}.roots")
    features = unique!(a[:features], "#{at}.features") |> Enum.sort()
    feature_map = Map.new(optional)
    for feature <- features, not Map.has_key?(feature_map, feature), do: fail!(:unknown_feature, "#{at}.features", "unknown feature #{inspect(feature)}", %{allowed: Map.keys(feature_map) |> Enum.sort()})
    selected = a[:roots] ++ a[:include] ++ Enum.flat_map(features, &Map.fetch!(feature_map, &1))
    if Enum.any?(a[:external], &(&1 in selected)), do: fail!(:unsupported_combination, "#{at}.external", "external boundary overlaps roots, includes or enabled features")
    a = a |> Keyword.put(:features, features) |> Keyword.put(:verify, verification!(a[:verify], a[:layout], at))
      |> Keyword.put(:inputs, declarations!(a[:inputs], false, "#{at}.inputs"))
    layout!(a[:layout], a, at)
  end

  defp verification!(raw, layout, at) do
    path = at <> ".verify"
    verify = validate!(raw, @verify, path)
    if not verify[:hex_build] and (verify[:hex_publish_check] or not Keyword.has_key?(raw, :hex_publish_check)), do: fail!(:unsupported_combination, path <> ".hex_publish_check", "hex_build: false requires explicit hex_publish_check: false")
    if verify[:component_tests] and layout != :components, do: fail!(:unsupported_combination, path <> ".component_tests", "component_tests requires components layout")
    if layout == :flat and (verify[:artifact_tests] != [] or not is_nil(verify[:smoke])), do: fail!(:unsupported_combination, path, "flat does not support artifact_tests or smoke")
    if layout == :preserve and verify[:artifact_tests] != [], do: fail!(:unsupported_combination, path <> ".artifact_tests", "preserve verifies the native project's tests")
    paths!(verify[:artifact_tests], path <> ".artifact_tests", false)
    tests = verify[:artifact_tests]
    context = unique!(verify[:context], path <> ".context") |> Enum.sort()
    for name <- context, not Regex.match?(~r/\A[A-Za-z_][A-Za-z0-9_.:-]*\z/, name), do: fail!(:invalid_context, path <> ".context", "context names must be public identifiers")
    smoke = if is_nil(verify[:smoke]), do: nil, else: validate!(verify[:smoke], @smoke, path <> ".smoke")
    if smoke, do: path!(smoke[:entry_file], path <> ".smoke.entry_file")
    verify |> Keyword.put(:smoke, smoke) |> Keyword.put(:artifact_tests, tests) |> Keyword.put(:context, context)
  end

  defp layout!(:preserve, a, at) do
    forbid!(a, [:package, :docs, :files, :flat], at)
    unless length(a[:roots]) == 1 and a[:include] == [] and a[:features] == [], do: fail!(:unsupported_combination, at, "preserve requires one root and no include/features")
    preserve = validate!(a[:preserve] || [], @preserve, at <> ".preserve")
    files = paths!(preserve[:files], at <> ".preserve.files", false)
    nonempty!(files, at <> ".preserve.files")
    for path <- files, other <- files, path != other and String.starts_with?(path, other <> "/"), do: fail!(:overlapping_paths, at <> ".preserve.files", "preserve paths overlap: #{inspect(other)} and #{inspect(path)}")
    preserve = preserve |> Keyword.put(:files, files) |> Keyword.put(:inputs, declarations!(preserve[:inputs], false, at <> ".preserve.inputs"))
    Keyword.put(a, :preserve, preserve)
  end

  defp layout!(layout, a, at) do
    forbid!(a, [:preserve] ++ if(layout == :components, do: [:flat], else: []), at)
    package = validate!(a[:package] || [], @package, at <> ".package") |> package!(at <> ".package")
    docs = validate!(a[:docs] || [], @docs, at <> ".docs") |> docs!(at <> ".docs")
    files = validate!(a[:files] || [], @files, at <> ".files")
    files = Enum.map(files, fn {key, paths} -> {key, paths!(paths, "#{at}.files.#{key}", false)} end)
    a = a |> Keyword.put(:package, package) |> Keyword.put(:docs, docs) |> Keyword.put(:files, files)
    if layout == :flat do
      flat = validate!(a[:flat] || [], @flat, at <> ".flat")
      if flat[:readme], do: path!(flat[:readme], at <> ".flat.readme")
      flat = Enum.reduce([:shared_test_configs, :test_support], flat, fn key, acc -> Keyword.put(acc, key, paths!(flat[key], "#{at}.flat.#{key}", true)) end)
      flat = Keyword.put(flat, :extra_test_deps, unique!(flat[:extra_test_deps], at <> ".flat.extra_test_deps") |> Enum.sort())
      Keyword.put(a, :flat, flat)
    else
      a
    end
  end

  defp package!(package, at) do
    for {key, value} <- [name: package[:name], otp_app: Atom.to_string(package[:otp_app])], not Regex.match?(~r/\A[a-z][a-z0-9_]*\z/, value), do: fail!(:invalid_package, "#{at}.#{key}", "invalid Mix/Hex package name")
    unless match?({:ok, _}, Version.parse(package[:version])), do: fail!(:invalid_package, at <> ".version", "expected a valid semantic version")
    unless match?({:ok, _}, Version.parse_requirement(package[:elixir])), do: fail!(:invalid_package, at <> ".elixir", "expected an Elixir version requirement")
    links = string_map!(package[:links], at <> ".links")
    Enum.each(links, fn {_label, url} -> public_url!(url, at <> ".links") end)
    deps = package[:dev_deps] |> Enum.with_index() |> Enum.map(fn {dep, index} ->
      case dep do
        {app, requirement, opts} when is_atom(app) and is_binary(requirement) and is_list(opts) ->
          normalized = dependency!([requirement: requirement, opts: opts], "#{at}.dev_deps[#{index}]")
          only = List.wrap(normalized[:opts][:only])
          if only == [] or Enum.any?(only, &(&1 not in [:dev, :test])) or normalized[:opts][:runtime] != false or Keyword.keys(opts) -- [:only, :runtime, :optional, :override, :hex, :repo, :organization] != [], do: fail!(:invalid_dependency, "#{at}.dev_deps[#{index}]", "development dependency must be Hex-only, scoped to dev/test and runtime: false")
          {app, requirement, normalized[:opts]}
        _ -> fail!(:invalid_dependency, "#{at}.dev_deps[#{index}]", "expected {app, requirement, options}")
      end
    end)
    unique!(Enum.map(deps, &elem(&1, 0)), at <> ".dev_deps")
    package |> Keyword.put(:links, links) |> Keyword.put(:dev_deps, Enum.sort_by(deps, &elem(&1, 0)))
  end

  defp docs!(docs, at) do
    for key <- [:main, :logo, :hook_file], docs[key], do: path!(docs[key], "#{at}.#{key}")
    if docs[:hook_file] && not docs[:mermaid], do: fail!(:unsupported_combination, at <> ".hook_file", "hook_file requires mermaid: true")
    for key <- [:homepage_url, :source_url], docs[key], do: public_url!(docs[key], "#{at}.#{key}")
    assets = string_map!(docs[:assets], at <> ".assets")
    Enum.each(assets, fn {source, target} -> path!(source, at <> ".assets"); path!(target, at <> ".assets") end)
    titles = string_map!(docs[:extra_titles], at <> ".extra_titles")
    Enum.each(Map.keys(titles), &path!(&1, at <> ".extra_titles"))
    groups = named!(docs[:groups_for_extras], at <> ".groups_for_extras") |> Enum.map(fn {label, paths} ->
      label = to_string(label)
      if label == "", do: fail!(:invalid_manifest, at <> ".groups_for_extras", "group labels must be nonempty")
      paths = paths!(paths, at <> ".groups_for_extras." <> label, false)
      nonempty!(paths, at <> ".groups_for_extras." <> label)
      {label, paths}
    end)
    docs |> Keyword.put(:assets, assets) |> Keyword.put(:extra_titles, titles) |> Keyword.put(:groups_for_extras, groups)
  end

  defp dependency!(raw, at) do
    value = validate!(raw, @dependency, at)
    opts = validate!(value[:opts], @dep_opts, at <> ".opts")
    git = opts[:git] || opts[:github]
    if opts[:git] && opts[:github], do: fail!(:conflicting_dependency, at <> ".opts", "git and github are mutually exclusive")
    if Enum.count([:branch, :tag, :ref], &Keyword.has_key?(opts, &1)) > 1, do: fail!(:conflicting_dependency, at <> ".opts", "only one of branch, tag or ref is allowed")
    if is_nil(git) and Enum.any?([:branch, :tag, :ref, :subdir, :sparse, :submodules, :depth], &Keyword.has_key?(opts, &1)), do: fail!(:invalid_dependency, at <> ".opts", "Git options require git or github")
    if git && Enum.any?([:hex, :repo, :organization], &Keyword.has_key?(opts, &1)), do: fail!(:conflicting_dependency, at <> ".opts", "Git and Hex source options are mutually exclusive")
    requirement = value[:requirement]
    unless (is_nil(requirement) and not is_nil(git)) or (is_binary(requirement) and match?({:ok, _}, Version.parse_requirement(requirement))), do: fail!(:invalid_dependency, at <> ".requirement", "a valid requirement is required unless using git/github")
    for key <- [:only, :targets], Keyword.has_key?(opts, key) do
      values = List.wrap(opts[key])
      unless values != [] and Enum.all?(values, &(is_atom(&1) and &1 not in [nil, true, false])), do: fail!(:invalid_dependency, "#{at}.opts.#{key}", "expected an atom or a nonempty list of atoms")
      unique!(values, "#{at}.opts.#{key}")
    end
    if opts[:hex] && not (is_binary(opts[:hex]) or is_atom(opts[:hex])), do: fail!(:invalid_dependency, at <> ".opts.hex", "expected package name")
    if Keyword.has_key?(opts, :app) and not (is_atom(opts[:app]) and opts[:app] != nil), do: fail!(:invalid_dependency, at <> ".opts.app", "expected application atom or false")
    if Keyword.has_key?(opts, :compile) and not (is_binary(opts[:compile]) or opts[:compile] == false), do: fail!(:invalid_dependency, at <> ".opts.compile", "expected a command string or false")
    if opts[:system_env], do: string_map!(opts[:system_env], at <> ".opts.system_env")
    for key <- [:subdir, :sparse], opts[key], do: path!(opts[key], "#{at}.opts.#{key}")
    for key <- [:git], opts[key], do: public_url!(opts[key], "#{at}.opts.#{key}")
    Keyword.put(value, :opts, Weld.Graph.normalize_dependency_options(opts))
  end

  defp declarations!(declarations, project?, at) when is_list(declarations) do
    declarations |> Enum.with_index() |> Enum.map(fn {value, i} -> declaration!(value, project?, "#{at}[#{i}]") end)
    |> then(fn values -> unique!(Enum.map(values, & &1[:path]), at); Enum.sort_by(values, & &1[:path]) end)
  end
  defp declarations!(_, _, at), do: fail!(:invalid_manifest, at, "expected a list of input declarations")

  defp declaration!(raw, project?, at) do
    value = validate!(raw, if(project?, do: @project_input, else: @input), at)
    path!(value[:path], at <> ".path", false, value[:type] == :glob)
    if project? do
      roles = unique!(value[:roles], at <> ".roles") |> Enum.sort()
      nonempty!(roles, at <> ".roles")
      published = Enum.any?(roles, &(&1 in [:native, :runtime, :compile, :docs]))
      if published and Enum.any?(roles, &(&1 in [:test, :metadata, :lock, :generation, :structure, :verification])) and not Keyword.has_key?(raw, :publish), do: fail!(:unsupported_combination, at <> ".publish", "mixed input roles require explicit publish: true/false")
      publish = Keyword.get(value, :publish, published)
      if publish and value[:target] == :none, do: fail!(:unsupported_combination, at <> ".target", "published input requires target: :relative")
      value |> Keyword.put(:publish, publish) |> Keyword.put(:roles, roles)
    else
      value
    end
  end

  # Audit every nested option object before applying defaults; duplicate keys must
  # never disappear through Keyword.get/Map.new, including string-keyed collections.
  defp audit(raw) do
    closed_errors(raw, @root, "manifest") ++
      Enum.flat_map([workspace: @workspace, classify: @classify, publication: @publication], fn {key, schema} -> optional_closed(raw, key, schema, to_string(key)) end) ++
      named_errors(get(raw, :publication, []) |> get(:optional, []), "publication.optional") ++
      audit_named(get(raw, :dependencies, []), "dependencies", fn value, path -> closed_errors(value, @dependency, path) ++ optional_closed(value, :opts, @dep_opts, path <> ".opts") end) ++
      audit_named(get(raw, :project_inputs, []), "project_inputs", &audit_inputs(&1, @project_input, &2)) ++
      audit_named(get(raw, :artifacts, []), "artifacts", &audit_artifact/2)
  end

  defp audit_artifact(raw, path) do
    closed_errors(raw, @artifact, path) ++
      Enum.flat_map([package: @package, docs: @docs, files: @files, preserve: @preserve, flat: @flat, verify: @verify], fn {key, schema} -> optional_closed(raw, key, schema, path <> "." <> to_string(key)) end) ++
      audit_inputs(get(raw, :inputs, []), @input, path <> ".inputs") ++
      audit_inputs(get(raw, :preserve, []) |> get(:inputs, []), @input, path <> ".preserve.inputs") ++
      optional_closed(get(raw, :verify, []), :smoke, @smoke, path <> ".verify.smoke") ++
      Enum.flat_map([:assets, :extra_titles, :groups_for_extras], fn key -> named_errors(get(raw, :docs, []) |> get(key, []), path <> ".docs." <> to_string(key)) end) ++
      named_errors(get(raw, :package, []) |> get(:links, []), path <> ".package.links") ++
      audit_dev_deps(get(raw, :package, []) |> get(:dev_deps, []), path <> ".package.dev_deps")
  end

  defp audit_dev_deps(values, path) when is_list(values), do: values |> Enum.with_index() |> Enum.flat_map(fn
    {{_, _, opts}, i} -> closed_errors(opts, @dep_opts, "#{path}[#{i}].opts")
    _ -> []
  end)
  defp audit_dev_deps(_, _), do: []
  defp audit_inputs(values, schema, path) when is_list(values), do: values |> Enum.with_index() |> Enum.flat_map(fn {value, i} -> closed_errors(value, schema, "#{path}[#{i}]") end)
  defp audit_inputs(_, _, _), do: []
  defp audit_named(value, path, fun) do
    named_errors(value, path) ++ if(is_list(value) or is_map(value), do: Enum.flat_map(value, fn
      {key, nested} when is_atom(key) or is_binary(key) -> fun.(nested, path <> "." <> to_string(key))
      _ -> []
    end), else: [])
  end
  defp optional_closed(raw, key, schema, path) do
    case get(raw, key, nil) do
      nil -> []
      value -> closed_errors(value, schema, path)
    end
  end
  defp closed_errors(raw, schema, path) do
    if Keyword.keyword?(raw) do
      keys = Keyword.keys(raw)
      duplicates = keys -- Enum.uniq(keys)
      unknown = Enum.uniq(keys -- Keyword.keys(schema))
      Enum.map(Enum.uniq(duplicates), &diagnostic(:duplicate_key, path <> "." <> to_string(&1), "duplicate key")) ++
        Enum.map(unknown, &diagnostic(:unknown_key, path <> "." <> to_string(&1), "unknown key", %{allowed: Keyword.keys(schema)}))
    else
      [diagnostic(:invalid_manifest, path, "expected a keyword list")]
    end
  end
  defp named_errors(value, path) when is_map(value), do: named_errors(Map.to_list(value), path)
  defp named_errors(value, path) when is_list(value) do
    if Enum.all?(value, fn item -> match?({key, _} when is_atom(key) or is_binary(key), item) end) do
      keys = Enum.map(value, fn {key, _} -> to_string(key) end)
      Enum.uniq(keys -- Enum.uniq(keys)) |> Enum.map(&diagnostic(:duplicate_key, path <> "." <> &1, "duplicate normalized key"))
    else
      [diagnostic(:invalid_manifest, path, "expected key/value pairs")]
    end
  end
  defp named_errors(_, path), do: [diagnostic(:invalid_manifest, path, "expected key/value pairs")]
  defp named!(value, path) do
    case named_errors(value, path) do
      [] -> if(is_map(value), do: Enum.sort_by(value, fn {key, _} -> to_string(key) end), else: value)
      [error | _] -> throw({:manifest_error, error})
    end
  end
  defp get(value, key, default), do: if(Keyword.keyword?(value), do: Keyword.get(value, key, default), else: default)

  defp validate!(value, schema, path) do
    case closed_errors(value, schema, path) do
      [] -> :ok
      [error | _] -> throw({:manifest_error, error})
    end
    case NimbleOptions.validate(value, schema) do
      {:ok, normalized} -> for {key, _} <- schema, Keyword.has_key?(normalized, key), do: {key, normalized[key]}
      {:error, error} -> fail!(:invalid_manifest, path, Exception.message(error), %{allowed: Keyword.keys(schema)})
    end
  end
  defp string_map!(value, path) do
    named!(value, path) |> Map.new(fn
      {key, val} when is_binary(key) and key != "" and is_binary(val) and val != "" -> {key, val}
      _ -> fail!(:invalid_manifest, path, "expected nonempty string keys and values")
    end)
  end
  defp public_url!(url, path) do
    uri = URI.parse(url)
    secret_query? = is_binary(uri.query) and Regex.match?(~r/(?:^|&)(?:token|api_key|password|secret|access_token)=/i, uri.query)
    if (uri.scheme in ["http", "https"] and not is_nil(uri.userinfo)) or secret_query?,
      do: fail!(:unsafe_context, path, "credentials must be supplied through the shell, not portable URLs")
  end
  defp name!(value, path) when is_atom(value) or is_binary(value) do
    name = to_string(value)
    unless Regex.match?(~r/\A[A-Za-z0-9][A-Za-z0-9_-]*\z/, name), do: fail!(:unsafe_path, path, "expected a safe identifier")
    name
  end
  defp name!(_, path), do: fail!(:invalid_manifest, path, "expected a string or atom identifier")
  defp paths!(values, at, dot?, glob? \\ false)
  defp paths!(values, at, dot?, glob?) when is_list(values) do
    unique!(values, at)
    Enum.each(values, &path!(&1, at, dot?, glob?))
    Enum.sort(values)
  end
  defp paths!(_, at, _, _), do: fail!(:invalid_manifest, at, "expected a list of paths")
  defp path!(path, at, dot? \\ false, glob? \\ false)
  defp path!(".", _at, true, _), do: :ok
  defp path!(path, at, _dot?, glob?) do
    try do
      Inventory.validate_path!(path)
      if Regex.match?(~r/\A[A-Za-z]:/, path) or Enum.any?(String.split(path, "/"), &(&1 in ~w(.ssh .hex .netrc .git-credentials .env .env.local .env.production id_rsa id_ed25519))) or (not glob? and String.contains?(path, ["*", "?", "[", "]", "{", "}"])), do: raise(ArgumentError, "unsafe or non-literal path")
    rescue
      _ in ArgumentError -> fail!(:unsafe_path, at, "expected a contained portable relative path")
    end
    :ok
  end
  defp workspace_root!(root) do
    if not String.valid?(root) or root == "" or Path.type(root) != :relative or String.contains?(root, ["\\", <<0>>]) or Regex.match?(~r/\A[A-Za-z]:/, root), do: fail!(:unsafe_path, "workspace.root", "expected a relative path from the manifest directory")
  end
  defp forbid!(a, keys, path), do: Enum.each(keys, fn key -> if Keyword.has_key?(a, key), do: fail!(:unsupported_combination, "#{path}.#{key}", "option is not allowed for this layout") end)
  defp unique!(values, at) do
    unless Enum.uniq(values) == values, do: fail!(:duplicate_value, at, "duplicate values are not allowed")
    values
  end
  defp nonempty!([], at), do: fail!(:invalid_manifest, at, "must be nonempty")
  defp nonempty!(_, _), do: :ok
  defp disjoint!(groups, at) do
    memberships = Enum.flat_map(groups, fn {group, ids} -> Enum.map(ids, &{&1, group}) end) |> Enum.group_by(&elem(&1, 0))
    for {id, entries} <- Enum.sort(memberships), length(entries) > 1, do: fail!(:overlapping_classification, at, "project #{inspect(id)} occurs in multiple groups", %{groups: Enum.map(entries, &elem(&1, 1))})
  end
  defp fail!(code, path, message, details \\ %{}), do: throw({:manifest_error, diagnostic(code, path, message, details)})
  defp diagnostic(code, path, message, details \\ %{}), do: %{
    code: code, severity: :error, phase: :manifest, artifact: artifact_path(path), project: nil,
    source: nil, target: nil, message: path <> ": " <> message,
    hint: "Use the schema 2 manifest fields and declared layout options.", details: Map.put(details, :path, path)
  }
  defp artifact_path("artifacts." <> rest), do: rest |> String.split(".") |> hd()
  defp artifact_path(_), do: nil
end
