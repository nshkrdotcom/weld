defmodule Weld.Core.Manifest do
  @moduledoc """
  Validate the trusted, evaluated v2 manifest term without accessing the host.

  The returned term has explicit defaults and typed declarations. Discovery and
  Mix metadata (including preserve package identity) are supplied by the shell.
  """

  alias Weld.Error

  @roles ~w(runtime compiled native test docs metadata generation)a
  @root [
    schema: [type: {:in, [2]}, required: true],
    workspace: [type: :keyword_list, required: true],
    classify: [type: :keyword_list, default: []],
    publication: [type: :keyword_list, default: []],
    dependencies: [type: :keyword_list, default: []],
    project_inputs: [type: :keyword_list, default: []],
    artifacts: [type: :keyword_list, required: true]
  ]
  @artifact [
    layout: [type: {:in, [:components, :flat, :preserve]}, required: true],
    roots: [type: {:list, :string}, required: true],
    include: [type: {:list, :string}, default: []],
    features: [type: {:list, :string}, default: []],
    external: [type: {:list, :string}, default: []],
    inputs: [type: {:list, :keyword_list}, default: []],
    package: [type: :keyword_list],
    docs: [type: :keyword_list],
    files: [type: :keyword_list],
    preserve: [type: :keyword_list],
    flat: [type: :keyword_list],
    verify: [type: :keyword_list, default: []]
  ]
  @package [
    name: [type: :string, required: true],
    otp_app: [type: :atom, required: true],
    version: [type: :string, required: true],
    elixir: [type: :string, default: "~> 1.18"],
    description: [type: :string, default: "Generated by Weld"],
    licenses: [type: {:list, :string}, default: ["MIT"]],
    links: [type: :any, default: %{}],
    dev_deps: [type: {:list, :any}, default: []]
  ]
  @verify [
    artifact_tests: [type: {:list, :string}, default: []],
    component_tests: [type: :boolean, default: false],
    hex_build: [type: :boolean, default: true],
    hex_publish_check: [type: :boolean, default: true],
    smoke: [type: :any, default: nil],
    context: [type: {:list, :string}, default: []]
  ]

  @spec normalize(term()) :: {:ok, keyword()} | {:error, [map()]}
  def normalize(term) do
    {:ok, normalize!(term)}
  rescue
    error in [Error, NimbleOptions.ValidationError, ArgumentError] ->
      {:error,
       [
         %{
           code: :invalid_manifest,
           severity: :error,
           phase: :manifest,
           message: Exception.message(error)
         }
       ]}
  end

  def normalize!(raw) do
    reject_duplicates!(raw, "manifest")
    config = validate!(raw, @root, "manifest (schema: 2 required)")

    workspace =
      validate!(
        config[:workspace],
        [
          root: [type: :string, required: true],
          projects: [type: {:list, :string}, required: true]
        ],
        "workspace"
      )

    unique_nonempty!(workspace[:projects], "workspace.projects")
    Enum.each(workspace[:projects], &safe_path!(&1, true))

    artifacts =
      Enum.map(config[:artifacts], fn {id, artifact} ->
        name = to_string(id)

        unless Regex.match?(~r/\A[A-Za-z0-9][A-Za-z0-9_-]*\z/, name),
          do: raise(Error, "invalid artifact id: #{name}")

        {id, artifact!(artifact, name)}
      end)

    unique_nonempty!(Enum.map(artifacts, fn {id, _} -> to_string(id) end), "artifacts")

    inputs =
      Map.new(config[:project_inputs], fn {id, declarations} ->
        id = to_string(id)
        safe_path!(id, true)
        {id, Enum.map(declarations, &declaration!(&1, true))}
      end)

    config
    |> Keyword.put(:workspace, workspace)
    |> Keyword.put(:artifacts, artifacts)
    |> Keyword.put(:project_inputs, inputs)
  end

  defp artifact!(raw, name) do
    a = validate!(raw, @artifact, "artifacts.#{name}")
    unique_nonempty!(a[:roots], "#{name}.roots")

    for key <- [:roots, :include, :external] do
      unique!(a[key], "#{name}.#{key}")
      Enum.each(a[key], &safe_path!(&1, true))
    end

    unique!(a[:features], "#{name}.features")

    if Enum.any?(a[:external], &(&1 in (a[:roots] ++ a[:include]))),
      do: raise(Error, "external boundary overlaps roots/includes")

    verify = validate!(a[:verify], @verify, "#{name}.verify")

    if not verify[:hex_build] and verify[:hex_publish_check],
      do: raise(Error, "hex_publish_check requires hex_build")

    if verify[:component_tests] and a[:layout] != :components,
      do: raise(Error, "component_tests requires components layout")

    smoke =
      if verify[:smoke],
        do:
          validate!(verify[:smoke], [entry_file: [type: :string, required: true]], "verify.smoke")

    verify = Keyword.put(verify, :smoke, smoke)

    a =
      a
      |> Keyword.put(:verify, verify)
      |> Keyword.update!(:inputs, &Enum.map(&1, fn d -> declaration!(d, false) end))

    case a[:layout] do
      :preserve ->
        forbid!(a, [:package, :docs, :files, :flat], name)

        unless length(a[:roots]) == 1 and a[:include] == [] and a[:features] == [],
          do: raise(Error, "preserve requires one root and no include/features")

        preserve =
          validate!(
            a[:preserve] || [],
            [
              files: [type: {:list, :string}, required: true],
              inputs: [type: {:list, :keyword_list}, default: []]
            ],
            "#{name}.preserve"
          )

        unique_nonempty!(preserve[:files], "preserve.files")
        Enum.each(preserve[:files], &safe_path!(&1, false))

        Keyword.put(
          a,
          :preserve,
          Keyword.update!(preserve, :inputs, &Enum.map(&1, fn d -> declaration!(d, false) end))
        )

      layout ->
        forbid!(a, [:preserve] ++ if(layout == :components, do: [:flat], else: []), name)
        package = validate!(a[:package] || [], @package, "#{name}.package")

        files =
          validate!(
            a[:files] || [],
            [
              docs: [type: {:list, :string}, default: []],
              assets: [type: {:list, :string}, default: []]
            ],
            "#{name}.files"
          )

        Enum.each(files[:docs] ++ files[:assets], &safe_path!(&1, false))

        flat =
          validate!(
            a[:flat] || [],
            [
              readme: [type: :string],
              shared_test_configs: [type: {:list, :string}, default: []],
              extra_test_deps: [type: {:list, :atom}, default: []],
              test_support: [type: {:list, :string}, default: []]
            ],
            "#{name}.flat"
          )

        a
        |> Keyword.put(:package, package)
        |> Keyword.put(:files, files)
        |> Keyword.put(:flat, flat)
    end
  end

  defp declaration!(raw, project?) do
    schema = [
      path: [type: :string, required: true],
      type: [type: {:in, [:file, :tree, :glob]}, required: true],
      required: [type: :boolean, default: true]
    ]

    schema =
      if project?,
        do:
          schema ++
            [
              roles: [type: {:list, {:in, @roles}}, required: true],
              target: [type: {:in, [:relative, :none]}, required: true],
              publish: [type: :boolean]
            ],
        else: schema

    value = validate!(raw, schema, "input declaration")
    safe_path!(value[:path], false)

    if project? do
      unique_nonempty!(value[:roles], "input.roles")
      published = Enum.any?(value[:roles], &(&1 in [:native, :runtime, :compiled, :docs]))

      if published and Enum.any?(value[:roles], &(&1 in [:test, :metadata, :generation])) and
           not Keyword.has_key?(value, :publish),
         do: raise(Error, "mixed input roles require explicit publish")

      publish = Keyword.get(value, :publish, published)

      if publish and value[:target] == :none,
        do: raise(Error, "published input requires a target")

      Keyword.put(value, :publish, publish)
    else
      value
    end
  end

  defp validate!(term, schema, label) do
    case NimbleOptions.validate(term, schema) do
      {:ok, normalized} -> normalized
      {:error, error} -> raise Error, "#{label}: #{Exception.message(error)}"
    end
  end

  defp forbid!(options, keys, name) do
    for key <- keys,
        Keyword.has_key?(options, key),
        do: raise(Error, "#{name}.#{key} is not allowed for this layout")
  end

  defp unique_nonempty!(values, label) do
    if values == [], do: raise(Error, "#{label} must be nonempty")
    unique!(values, label)
  end

  defp unique!(values, label) do
    unless Enum.uniq(values) == values, do: raise(Error, "duplicate values in #{label}")
  end

  defp safe_path!(".", true), do: :ok

  defp safe_path!(path, _) do
    Weld.Core.Inventory.validate_path!(path)
    :ok
  end

  defp reject_duplicates!(value, path) when is_list(value) do
    if Keyword.keyword?(value) do
      unique!(Keyword.keys(value), path)
      Enum.each(value, fn {key, nested} -> reject_duplicates!(nested, "#{path}.#{key}") end)
    else
      Enum.each(value, &reject_duplicates!(&1, path))
    end
  end

  defp reject_duplicates!(value, path) when is_tuple(value),
    do: reject_duplicates!(Tuple.to_list(value), path)

  defp reject_duplicates!(value, path) when is_map(value),
    do: Enum.each(value, fn {key, nested} -> reject_duplicates!(nested, "#{path}.#{key}") end)

  defp reject_duplicates!(_, _), do: :ok
end
